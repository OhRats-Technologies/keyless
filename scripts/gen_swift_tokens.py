#!/usr/bin/env python3
"""Generate ``packaging/macos/Keyless/Tokens.swift`` from ``design-tokens.json``.

The JSON file is the single source of truth for the OhRats design tokens; both
the Qt shell (``keyless.ui.theme.tokens``) and the SwiftUI shell consume it.
Run this after editing the JSON and commit the regenerated Swift file.

Usage: python scripts/gen_swift_tokens.py [--check]
  --check fails (exit 1) if the committed file differs from the regenerated one.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TOKENS_PATH = REPO / "src" / "keyless" / "ui" / "theme" / "design-tokens.json"
OUTPUT_PATH = REPO / "packaging" / "macos" / "Keyless" / "Tokens.swift"

HEADER = '''// Generated by scripts/gen_swift_tokens.py from src/keyless/ui/theme/design-tokens.json.
// Do not edit by hand: edit the JSON and regenerate. This keeps the SwiftUI
// shell on the same token grid as the Qt shell and the OhRats UI kit.

import SwiftUI

enum Tokens {
'''


def _hex_color(name: str, value: str) -> str:
    assert value.startswith("#") and len(value) == 7, (name, value)
    r, g, b = (int(value[i : i + 2], 16) for i in (1, 3, 5))
    return (
        f"    static let {name} = Color(red: {r} / 255.0, green: {g} / 255.0, "
        f"blue: {b} / 255.0)  // {value}"
    )


def render(tokens: dict) -> str:
    lines = [HEADER.rstrip("\n"), ""]
    lines.append("    // MARK: Palette")
    lines.append("")
    for theme_name in ("light", "dark"):
        palette = tokens["themes"][theme_name]
        lines.append(f"    enum {theme_name.capitalize()} {{")
        for key, value in palette.items():
            lines.append(_hex_color(key, value).replace("    ", "        ", 1))
        lines.append("    }")
        lines.append("")
    lines.append("    // MARK: Spacing (pt)")
    lines.append("")
    for key, value in tokens["spacing"].items():
        lines.append(f"    static let space_{'XS' if key == 'xs' else key.upper()} = {value}.0")
    lines.append("")
    lines.append("    // MARK: Radii (pt)")
    lines.append("")
    for key, value in tokens["radii"].items():
        lines.append(f"    static let radius_{key.capitalize()} = {value}.0")
    lines.append("")
    lines.append("    // MARK: Typography")
    lines.append("")
    lines.append('    static let fontFamily = "Inter"')
    lines.append('    static let monoFontFamily = "Space Mono"')
    lines.append("")
    for key, value in tokens["typography"]["sizes"].items():
        lines.append(f"    static let fontSize_{'S' if key == 'small' else key.capitalize()} = {value}.0")
    lines.append("")
    lines.append("    // MARK: Text styles")
    lines.append("")
    lines.append("    static func body() -> Font { .custom(fontFamily, size: fontSize_body) }")
    lines.append("    static func heading() -> Font { .custom(fontFamily, size: fontSize_heading) }")
    lines.append("    static func title() -> Font { .custom(fontFamily, size: fontSize_title) }")
    lines.append("    static func small() -> Font { .custom(fontFamily, size: fontSize_S) }")
    lines.append("    static func telemetry() -> Font { .custom(monoFontFamily, size: fontSize_S) }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed Tokens.swift differs from the regenerated output",
    )
    args = parser.parse_args(argv)
    tokens = json.loads(TOKENS_PATH.read_text())
    rendered = render(tokens)
    if args.check:
        current = OUTPUT_PATH.read_text() if OUTPUT_PATH.exists() else ""
        if current != rendered:
            print(f"STALE: {OUTPUT_PATH} differs from design-tokens.json; regenerate.", file=sys.stderr)
            return 1
        return 0
    OUTPUT_PATH.write_text(rendered)
    print(f"wrote {OUTPUT_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
